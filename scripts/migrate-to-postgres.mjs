import fs from 'node:fs';
import path from 'node:path';
import { randomBytes, createHash } from 'node:crypto';
import Database from 'better-sqlite3';
import pg from 'pg';

process.loadEnvFile('.env.local');
if (!process.env.DATABASE_ADMIN_URL) throw new Error('DATABASE_ADMIN_URL is required');
if (process.env.DATABASE_URL) throw new Error('DATABASE_URL already exists; refusing to replace a configured database');
const name = 'restapp';
const quote = value => '"' + value.replaceAll('"', '""') + '"';
const tables = ['users','sessions','customers','projects','accounts','transactions','transaction_lines','invoices','invoice_lines','time_entries','reports','report_rows','settings'];
const backupDir = path.resolve('data/backups');
fs.mkdirSync(backupDir, { recursive: true, mode: 0o700 });
const stamp = new Date().toISOString().replaceAll(/[:.]/g, '-');
const backupPath = path.join(backupDir, `stapp-before-postgres-${stamp}.db`);
const source = new Database(process.env.STAPP_DATABASE_PATH || 'data/stapp.db', { fileMustExist: true });
const admin = new pg.Client({ connectionString: process.env.DATABASE_ADMIN_URL, connectionTimeoutMillis: 10_000 });
let target;
let sourceLocked = false;
try {
  await admin.connect();
  const conflicts = await admin.query('SELECT datname FROM pg_database WHERE datname=$1 UNION ALL SELECT rolname FROM pg_roles WHERE rolname=$1', [name]);
  const resumePath = process.env.STAPP_RESUME_CREDENTIALS;
  if (conflicts.rowCount && !resumePath) throw new Error('Project database or role already exists; refusing to overwrite');
  if (resumePath && conflicts.rowCount !== 2) throw new Error('Resume requires the previously provisioned role and database');
  // Hold a writer reservation throughout snapshot, copy and cutover. Reads continue.
  source.exec('BEGIN IMMEDIATE');
  sourceLocked = true;
  if (source.pragma('quick_check')[0].quick_check !== 'ok' || source.pragma('foreign_key_check').length) throw new Error('SQLite integrity checks failed');
  const actual = source.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").all().map(x => x.name).sort();
  if (JSON.stringify(actual) !== JSON.stringify([...tables].sort())) throw new Error('Unexpected source tables; review migration before continuing');
  // Back up through a second reader, since the locking connection has an open transaction.
  const reader = new Database(source.name, { readonly: true });
  try { await reader.backup(backupPath); } finally { reader.close(); }
  fs.chmodSync(backupPath, 0o600);
  let url;
  if (resumePath) {
    const saved = fs.readFileSync(resumePath, 'utf8').trim();
    url = new URL(saved.replace(/^DATABASE_URL=/, ''));
    const adminUrl = new URL(process.env.DATABASE_ADMIN_URL);
    if (url.host !== adminUrl.host || url.username !== name || url.pathname !== '/' + name) throw new Error('Resume credentials do not match the project target');
  } else {
    const password = randomBytes(36).toString('base64url');
    url = new URL(process.env.DATABASE_ADMIN_URL);
    url.username = name; url.password = password; url.pathname = '/' + name;
    const credentialsPath = path.join(backupDir, `postgres-credentials-${stamp}.env`);
    fs.writeFileSync(credentialsPath, `DATABASE_URL=${url.href}\n`, { mode: 0o600, flag: 'wx' });
    await admin.query(`CREATE ROLE ${quote(name)} LOGIN PASSWORD '${password}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS`);
    await admin.query(`CREATE DATABASE ${quote(name)} OWNER ${quote(name)} TEMPLATE template0 ENCODING 'UTF8'`);
    await admin.query(`REVOKE ALL ON DATABASE ${quote(name)} FROM PUBLIC`);
  }
  target = new pg.Client({ connectionString: url.href, connectionTimeoutMillis: 10_000 });
  await target.connect();
  const existing = await target.query("SELECT tablename FROM pg_tables WHERE schemaname NOT IN ('pg_catalog','information_schema')");
  if (existing.rowCount) throw new Error('Target is not empty; refusing to modify existing tables');
  await target.query('BEGIN');
  await target.query('REVOKE CREATE ON SCHEMA public FROM PUBLIC');
  const summary = { database: name, role: name, backup: backupPath, tables: {}, verified: false };
  for (const table of tables) {
    const {sql} = source.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name=?").get(table);
    const converted = sql
      .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/\bINTEGER\b/g, 'BIGINT')
      .replace(/\s+COLLATE NOCASE/g, '')
      .replace(/DEFAULT CURRENT_TIMESTAMP/g, 'DEFAULT (CURRENT_TIMESTAMP::text)')
      .replace(/ON DELETE (CASCADE|RESTRICT|SET NULL)/g, '$& DEFERRABLE INITIALLY DEFERRED');
    await target.query(converted);
    const columns = source.pragma(`table_info(${quote(table)})`);
    const key = columns.find(c => c.pk).name;
    const data = source.prepare(`SELECT * FROM ${quote(table)} ORDER BY ${quote(key)}`).all();
    const names = columns.map(c=>c.name);
    for (let offset=0; offset<data.length; offset+=250) {
      const chunk = data.slice(offset,offset+250);
      const values = chunk.flatMap(row=>names.map(n=>row[n]));
      const placeholders = chunk.map((_,i)=>`(${names.map((_,j)=>'$'+(i*names.length+j+1)).join(',')})`).join(',');
      await target.query(`INSERT INTO ${quote(table)} (${names.map(quote).join(',')}) VALUES ${placeholders}`, values);
    }
    if (key === 'id') {
      const previous = source.prepare('SELECT seq FROM sqlite_sequence WHERE name=?').get(table)?.seq || 0;
      const maximum = Math.max(previous, ...data.map(row=>row.id), 0);
      await target.query('SELECT setval(pg_get_serial_sequence($1, $2), $3, $4)', [table,'id',Math.max(maximum,1),maximum>0]);
    }
    const copied = (await target.query(`SELECT * FROM ${quote(table)} ORDER BY ${quote(key)}`)).rows;
    // Compare every column of every row, including original timestamp text and hashes.
    const canonical = records => JSON.stringify(records.map(row=>names.map(n=>row[n] == null ? null : String(row[n]))));
    const hash = records => createHash('sha256').update(canonical(records)).digest('hex');
    if (hash(data) !== hash(copied)) throw new Error(`Full data verification failed: ${table}`);
    summary.tables[table] = { rows: data.length, sha256: hash(data) };
    console.log(`Verified ${table}: ${data.length} rows`);
  }
  await target.query('SET CONSTRAINTS ALL IMMEDIATE');
  for (const {sql} of source.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL").all()) await target.query(sql);
  await target.query('CREATE UNIQUE INDEX users_email_case_insensitive ON users (lower(email))');
  await target.query('SET CONSTRAINTS ALL IMMEDIATE');
  await target.query('COMMIT');
  summary.verified = true;
  fs.writeFileSync(path.join(backupDir, `postgres-migration-${stamp}.json`), JSON.stringify(summary,null,2)+'\n', { mode: 0o600 });
  // Only switch the application after the entire copy has committed and verified.
  const envPath = path.resolve('.env.local');
  const env = fs.readFileSync(envPath,'utf8');
  if (/^\s*(?:export\s+)?DATABASE_URL\s*=/m.test(env)) throw new Error('DATABASE_URL was added during migration; refusing to overwrite');
  const tmp = envPath + '.migration-tmp';
  fs.writeFileSync(tmp, env.trimEnd()+`\nDATABASE_URL=${url.href}\n`, { mode: 0o600, flag:'wx' });
  fs.renameSync(tmp,envPath);
  console.log('Migration committed and DATABASE_URL configured. Backup:',backupPath);
} catch (error) {
  if (target) await target.query('ROLLBACK').catch(()=>{});
  console.error('Migration stopped:',error.message);
  process.exitCode=1;
} finally {
  if(sourceLocked)source.exec('ROLLBACK');
  source.close();
  if(target)await target.end();
  await admin.end();
}
