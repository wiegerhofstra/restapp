export async function migratePresets(client) {
  await client.query(`
    CREATE TABLE IF NOT EXISTS posting_presets (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      seed_key text UNIQUE, name text NOT NULL CHECK(length(name) BETWEEN 1 AND 100),
      version integer NOT NULL DEFAULT 1, active boolean NOT NULL DEFAULT true,
      expense_account_id bigint NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
      vat_mode text NOT NULL CHECK(vat_mode IN ('none','standard','reverse')),
      rate_bps integer NOT NULL CHECK(rate_bps BETWEEN 0 AND 10000),
      input_vat_account_id bigint REFERENCES accounts(id) ON DELETE RESTRICT,
      output_vat_account_id bigint REFERENCES accounts(id) ON DELETE RESTRICT,
      project_id bigint REFERENCES projects(id) ON DELETE RESTRICT,
      CHECK(vat_mode='none' OR input_vat_account_id IS NOT NULL),
      CHECK(vat_mode<>'reverse' OR output_vat_account_id IS NOT NULL)
    );
    CREATE TABLE IF NOT EXISTS posting_preset_rules (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      preset_id bigint NOT NULL REFERENCES posting_presets(id) ON DELETE CASCADE,
      field text NOT NULL CHECK(field IN ('iban','name','description')),
      pattern text NOT NULL CHECK(length(pattern) BETWEEN 3 AND 200),
      direction text NOT NULL CHECK(direction IN ('payment','refund','both')),
      UNIQUE(preset_id,field,pattern,direction)
    );
    CREATE TABLE IF NOT EXISTS transaction_preset_applications (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      transaction_id bigint NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
      preset_id bigint NOT NULL REFERENCES posting_presets(id) ON DELETE RESTRICT,
      snapshot jsonb NOT NULL, actor text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS preset_applications_transaction ON transaction_preset_applications(transaction_id);
  `);
  // Resolve the reviewed legacy chart by name and kind; never assume database IDs.
  const seeds = [
    ['netcup','Netcup','Netcup','reverse',['netcup']],
    ['google-apps','Google Apps','Google Apps','reverse',['google apps','google workspace']],
    ['transip','TransIP','Hosting','standard',['transip']],
  ];
  const account = async (name,kind) => {
    const result = await client.query('SELECT id FROM accounts WHERE name=$1 AND kind=$2 AND can_post=1',[name,kind]);
    return result.rows.length === 1 ? result.rows[0].id : null;
  };
  for (const [key,name,expense,mode,patterns] of seeds) {
    if ((await client.query('SELECT 1 FROM posting_presets WHERE seed_key=$1',[key])).rowCount) continue;
    const expenseId=await account(expense,'expense');
    const inputId=await account(mode==='reverse'?'BTW advanced 21% verlegd':'BTW advanced 21%','asset');
    const outputId=mode==='reverse'?await account('BTW 21% verlegd','liability'):null;
    if(!expenseId || !inputId || (mode==='reverse'&&!outputId)) continue;
    const preset=await client.query(`INSERT INTO posting_presets(seed_key,name,expense_account_id,vat_mode,rate_bps,input_vat_account_id,output_vat_account_id)
      VALUES($1,$2,$3,$4,2100,$5,$6) RETURNING id`,[key,name,expenseId,mode,inputId,outputId]);
    for(const pattern of patterns) await client.query("INSERT INTO posting_preset_rules(preset_id,field,pattern,direction) VALUES($1,'name',$2,'payment')",[preset.rows[0].id,pattern]);
  }
}
