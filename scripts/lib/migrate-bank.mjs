export async function migrateBank(client) {
  await client.query(`
    CREATE TABLE IF NOT EXISTS bank_accounts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      iban TEXT NOT NULL UNIQUE,
      account_id BIGINT NOT NULL UNIQUE REFERENCES accounts(id) ON DELETE RESTRICT
    );
    CREATE TABLE IF NOT EXISTS bank_imports (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      file_hash TEXT NOT NULL UNIQUE, filename TEXT NOT NULL, source_xml TEXT NOT NULL,
      bank_account_id BIGINT NOT NULL REFERENCES bank_accounts(id) ON DELETE RESTRICT,
      statements JSONB NOT NULL, entry_count INTEGER NOT NULL, new_count INTEGER NOT NULL DEFAULT 0,
      imported_by TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS bank_entries (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      bank_account_id BIGINT NOT NULL REFERENCES bank_accounts(id) ON DELETE RESTRICT,
      entry_key TEXT NOT NULL UNIQUE, bank_reference TEXT NOT NULL, service_reference TEXT NOT NULL,
      booking_date TEXT NOT NULL, value_date TEXT NOT NULL,
      amount_cents BIGINT NOT NULL CHECK(amount_cents <> 0),
      counterparty TEXT NOT NULL, counterparty_iban TEXT NOT NULL, reference TEXT NOT NULL, description TEXT NOT NULL,
      details JSONB NOT NULL, warning TEXT NOT NULL DEFAULT '',
      transaction_id BIGINT REFERENCES transactions(id) ON DELETE RESTRICT,
      resolution TEXT CHECK(resolution IN ('linked','created')),
      reviewed_by TEXT, reviewed_at TIMESTAMPTZ,
      CHECK ((transaction_id IS NULL AND resolution IS NULL) OR (transaction_id IS NOT NULL AND resolution IS NOT NULL)),
      UNIQUE(bank_account_id, transaction_id)
    );
    CREATE TABLE IF NOT EXISTS bank_import_entries (
      import_id BIGINT NOT NULL REFERENCES bank_imports(id) ON DELETE CASCADE,
      entry_id BIGINT NOT NULL REFERENCES bank_entries(id) ON DELETE RESTRICT,
      PRIMARY KEY(import_id, entry_id)
    );
    CREATE TABLE IF NOT EXISTS bank_review_events (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      entry_id BIGINT NOT NULL REFERENCES bank_entries(id) ON DELETE RESTRICT,
      action TEXT NOT NULL, transaction_id BIGINT, actor TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS bank_entries_account_date ON bank_entries(bank_account_id,booking_date);
    CREATE INDEX IF NOT EXISTS bank_entries_transaction ON bank_entries(transaction_id);
    CREATE INDEX IF NOT EXISTS bank_import_entries_entry ON bank_import_entries(entry_id);

    CREATE OR REPLACE FUNCTION protect_reconciled_bank_transaction() RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE target_id bigint;
    BEGIN
      IF TG_TABLE_NAME = 'transactions' THEN
        target_id := OLD.id;
      ELSIF TG_OP = 'INSERT' THEN
        target_id := NEW.transaction_id;
      ELSE
        target_id := OLD.transaction_id;
      END IF;
      -- Same lock as the importer: linking and manual edits cannot race.
      PERFORM pg_advisory_xact_lock(713053);
      IF EXISTS (SELECT 1 FROM bank_entries WHERE transaction_id = target_id) THEN
        RAISE EXCEPTION 'Unlink the bank entry before editing or deleting this transaction.';
      END IF;
      IF TG_TABLE_NAME = 'transaction_lines' AND TG_OP = 'UPDATE' THEN
        IF EXISTS (SELECT 1 FROM bank_entries WHERE transaction_id = NEW.transaction_id) THEN
          RAISE EXCEPTION 'Unlink the bank entry before editing or deleting this transaction.';
        END IF;
      END IF;
      IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
    END $$;
    DROP TRIGGER IF EXISTS protect_bank_transaction ON transactions;
    CREATE TRIGGER protect_bank_transaction BEFORE UPDATE OR DELETE ON transactions
      FOR EACH ROW EXECUTE FUNCTION protect_reconciled_bank_transaction();
    DROP TRIGGER IF EXISTS protect_bank_lines ON transaction_lines;
    CREATE TRIGGER protect_bank_lines BEFORE INSERT OR UPDATE OR DELETE ON transaction_lines
      FOR EACH ROW EXECUTE FUNCTION protect_reconciled_bank_transaction();
  `);
}
